# 3. ربط التطبيق بشيت جوجل (Google Sheets)
# ==========================================
def save_to_google_sheets(student_name, score, total):
    try:
        scopes = [
            "https://www.googleapis.com/auth/spreadsheets",
            "https://www.googleapis.com/auth/drive"
        ]
        credentials = Credentials.from_service_account_info(
            st.secrets["gcp_service_account"],
            scopes=scopes
        )
        client = gspread.authorize(credentials)
        sheet = client.open("درجات اختبار الأحياء - أ مروة السعدني").sheet1
        sheet.append_row([student_name, f"{score} / {total}"])
        return True
    except Exception as e:
        st.error(f"حدث خطأ أثناء حفظ النتيجة في الشيت: {e}")
        return False

