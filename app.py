# 2. دالة إظهار الصور التلقائية
# ==========================================
def display_question_image(q_id):
    """
    تبحث عن أي صورة باسم السؤال داخل مجلد images وتكون بامتداد png أو jpg أو jpeg
    """
    image_folder = "images"
    extensions = ["png", "jpg", "jpeg", "PNG", "JPG", "JPEG"]
    
    for ext in extensions:
        img_path = os.path.join(image_folder, f"q{q_id}.{ext}")
        if os.path.exists(img_path):
            st.image(img_path, caption=f"رسم توضيحي لسؤال رقم {q_id}", use_container_width=True)
            break

